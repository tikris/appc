  <h2>Un portail prêt à l'emploi pour les parents de chaque établissement</h2>
  <p>L'association Parents à Paris Centre met à disposition des représentants de parents d'élèves un portail dédié
     à chaque établissement scolaire :</p>
  <ul class="features">
    <li>💡 <strong>Consultations</strong> : les parents proposent des idées, votent et ajoutent des notes de contexte ;</li>
    <li>📊 <strong>Sondages</strong> : une question rapide, comme la date de la prochaine réunion ;</li>
    <li>🙋 <strong>Inscriptions bénévoles</strong> : des créneaux pour la fête de l'école ou une sortie ;</li>
    <li>📢 <strong>Annonces et agenda</strong> : les dates importantes de l'année au même endroit.</li>
  </ul>
  <p class="muted">L'accès à un portail se fait avec un code délivré par le représentant des parents de l'établissement.
     Si vous avez reçu un lien, ouvrez-le directement.</p>
